#!/usr/bin/env python3
"""Build hard negatives for fine-tuning the answer check, from DIKSHA text and rules only.

The answer check is weakest on a sentence that reuses a passage's words with one fact flipped.
Each row here takes a real sentence and flips a direction, negation, name, opposite or number.
No text is generated by a model. Every page behind tests/blind and tests/dev is left out, so
those sets stay fair.

    python3 training/build_hard_negatives.py
    python3 training/train_nli.py --data training/data_answer_check --base training/base/nli-deberta-v3-base
"""

from __future__ import annotations

import argparse
import collections
import json
import os
import random
import re
import sys

sys.path.insert(0, os.path.dirname(__file__))
import build_nli_data  # noqa: E402
from build_nli_data import CONTRADICTION, ENTAILMENT, clean_passages, flip, sentences, write  # noqa: E402

# Swapping "from" and "to" on its own only breaks the grammar, so it teaches nothing here.
for word in ("from", "to"):
    build_nli_data.SWAP.pop(word, None)

ROOT = os.path.join(os.path.dirname(__file__), "..")
_FROM_TO = re.compile(r"\bfrom (the |a |an )?([a-z]{3,}) to (the |a |an )?([a-z]{3,})\b", re.IGNORECASE)
_AUX = re.compile(r"\b(is|are|was|were|can|has|have|will)\b(?! not)")
_NOT = re.compile(r"\b(is|are|was|were|can|has|have|will|do|does|did) not\b")
_NAME = re.compile(r"(?<=[a-z,] )[A-Z][a-z]{3,}\b")


def held_out_pages():
    pages = set()
    for name in ("blind", "dev"):
        with open(os.path.join(ROOT, "tests", name, "passages.jsonl"), encoding="utf-8") as f:
            for line in f:
                p = json.loads(line)
                pages.add((p["content_id"], p["page"]))
    return pages


def swap_direction(sentence):
    m = _FROM_TO.search(sentence)
    if not m or m.group(2).lower() == m.group(4).lower():
        return None
    return sentence[:m.start()] + f"from {m.group(1) or ''}{m.group(4)} to {m.group(3) or ''}{m.group(2)}" + sentence[m.end():]


def flip_negation(sentence):
    m = _NOT.search(sentence)
    if m:
        return sentence[:m.start()] + m.group(1) + sentence[m.end():] if m.group(1) not in ("do", "does", "did") else None
    return _AUX.sub(lambda a: f"{a.group(1)} not", sentence, count=1) if _AUX.search(sentence) else None


def swap_name(sentence, names, rng):
    found = [n for n in _NAME.findall(sentence) if n in names]
    options = [n for n in names if n not in sentence]
    if not found or not options:
        return None
    return sentence.replace(rng.choice(found), rng.choice(options), 1)


def build(passages, rng, limit):
    # Only words seen across many pages, because one-off capitals are mostly OCR damage.
    counts = collections.Counter(n for p in passages for n in set(_NAME.findall(p["text"])))
    names = sorted(n for n, c in counts.items() if c >= 8)
    rows = []
    for p in passages[:limit]:
        for s in sentences(p["text"]):
            if s.endswith("?"):
                continue
            edits = [("direction", swap_direction(s)), ("negation", flip_negation(s)),
                     ("name", swap_name(s, names, rng)), ("opposite_or_number", flip(s, rng))]
            edits = [(kind, new) for kind, new in edits if new and new != s and new.split() != s.split()]
            if not edits:
                continue
            kind, new = rng.choice(edits)
            rows.append(dict(premise=p["text"], hypothesis=s, label=ENTAILMENT, task="support", source="hard_exact"))
            rows.append(dict(premise=p["text"], hypothesis=new, label=CONTRADICTION, task="support", source=f"hard_{kind}"))
            break
    return rows


def main() -> int:
    ap = argparse.ArgumentParser(description="Build rule-based hard negatives for the answer check.")
    ap.add_argument("--chunks", default=os.path.join(ROOT, "corpus/diksha_g7_all/index/chunks.jsonl"))
    ap.add_argument("--out", default=os.path.join(ROOT, "training/data_answer_check"))
    ap.add_argument("--limit", type=int, default=6000)
    ap.add_argument("--seed", type=int, default=29)
    args = ap.parse_args()
    rng = random.Random(args.seed)
    held_out = held_out_pages()
    passages = [p for p in clean_passages(args.chunks, rng) if (p["content_id"], p["page"]) not in held_out]
    os.makedirs(args.out, exist_ok=True)
    write(os.path.join(args.out, "support_hard.jsonl"), build(passages, rng, args.limit))
    return 0


if __name__ == "__main__":
    sys.exit(main())
